async def check():
    async with async_playwright() as p:
        browser = await p.chromium.launch(executable_path='/usr/bin/chromium', args=['--no-sandbox'])
        context = await browser.new_context(accept_downloads=True)
        errors = []
        async def isolate(route):
            u = urlparse(route.request.url)
            if u.hostname not in ['localhost', '127.0.0.1'] or (u.path.rstrip('/') == '/_next/image' and parse_qs(u.query).get('url',[''])[0].startswith('http')):
                await route.abort()
            elif u.path.startswith('/api/'):
                await route.fulfill(status=200, content_type='application/json', body='[]')
            else:
                await route.continue_()
        await context.route('**/*', isolate)
        page = await context.new_page()
        page.on('pageerror', lambda err: (errors.append(str(err)), print('ERROR',str(err),flush=True)))
        page.on('console', lambda msg: print('CONSOLE',msg.type,msg.text[:300],flush=True))
        page.on('request', lambda req: print('REQUEST',req.url[:180],flush=True) if 'simple-rabbit' in req.url else None)
        async def dialog(d):
            print('DIALOG',d.message,flush=True)
            await d.accept()
        page.on('dialog', dialog)
        results = []
        for slug in samples:
            print('Opening',slug,flush=True)
            await page.goto(base + '/printables/' + slug + '/', wait_until='networkidle',timeout=120000)
            await page.wait_for_timeout(1000)
            row={'slug':slug}
            for label in ['Download PDF','Download PNG']:
                async with page.expect_download(timeout=15000) as info:
                    await page.get_by_role('button',name=label,exact=True).click()
                dl=await info.value
                target=OUT/dl.suggested_filename
                await dl.save_as(target)
                row[label]={'file':target.name,'sha256':hashlib.sha256(target.read_bytes()).hexdigest()}
                if label.endswith('PDF'):
                    doc=fitz.open(target)
                    assert len(doc)==1 and abs(doc[0].rect.width-595.28)<1 and abs(doc[0].rect.height-841.89)<1
                    assert 'Generated by ConnectTheDotsPrintable.online' in doc[0].get_text()
                    imgs=doc[0].get_images()
                    assert len(imgs)==1
                    embedded=doc.extract_image(imgs[0][0])['image']
                    from io import BytesIO
                    import math
                    from PIL import ImageStat
                    expected=Image.open(ROOT/'public/generated/dot-to-dot/standalone-openclipart'/f'{slug}-puzzle.webp').convert('RGB')
                    difference=ImageChops.difference(expected,Image.open(BytesIO(embedded)).convert('RGB'))
                    rmse=math.sqrt(sum(ImageStat.Stat(difference).sum2)/(expected.width*expected.height*3))
                    assert rmse<5,rmse
                    row[label].update({'a4':True,'credit':True,'puzzle_pixel_rmse':rmse})
                else:
                    expected=Image.open(ROOT/'public/generated/dot-to-dot/standalone-openclipart'/f'{slug}-solution.webp').convert('RGB')
                    assert ImageChops.difference(expected,Image.open(target).convert('RGB')).getbbox() is None
                    row[label]['solution_pixels_match']=True
                print(slug,label,'PASS',flush=True)
            results.append(row)
            (OUT/'downloads.json').write_text(json.dumps(results,indent=2))
        (OUT/'errors.json').write_text(json.dumps(errors,indent=2))
        await browser.close()

asyncio.run(check())
